"""Controlled foreign-read canaries and fresh-run archive isolation.

Every canary is generated by this evaluator. No personal/peer files are read.
The deliberately contaminated session is never a pilot or main observation.
"""
from __future__ import annotations

import argparse
import json
import re
import threading
import uuid
from pathlib import Path

from acceptance import content_text
from contamination import Scope, audit, collect
from driver import DEFAULT_MODEL, PersistentSession
from grading import check_subscription, file_digest, write_new


def texts(results: dict) -> str:
    return "\n".join(t for values in results.values() for result in values for t in content_text(result.get("content")))


def session(args, root: Path, name: str) -> PersistentSession:
    check_subscription(args.claude, args.config)
    task = root / name / "task"
    task.mkdir(parents=True)
    (task / "probe.txt").write_text("CONTROL-" + uuid.uuid4().hex + "\n")
    return PersistentSession(binary=args.claude, config=args.config, model=DEFAULT_MODEL, workspace=task,
                             evidence=root / name / "evidence", plugin=Path(__file__).resolve().parents[2],
                             settings={"alwaysThinkingEnabled": True, "enabledPlugins": {}, "pluginConfigs": {
                                 "context-harness@inline": {"options": {"stopGate": "off", "toolGate": "off", "toolJev": "off",
                                     "instructions": "off", "foldJev": "off", "instructionFilter": "off", "foldAtPercent": 0}}}})


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", type=Path, required=True)
    parser.add_argument("--root", type=Path, required=True)
    parser.add_argument("--claude", type=Path, default=Path.home() / ".local/share/claude/versions/2.1.309")
    args = parser.parse_args()
    args.root.mkdir(parents=True, exist_ok=False, mode=0o700)
    runtime = Path(__file__).resolve().parent
    plugin = runtime.parents[1]
    inputs = [*(plugin / "hooks").glob("*.ts"), plugin / ".claude-plugin/plugin.json",
              *(runtime / f"{name}.py" for name in ["capture", "driver", "curl_transport", "grading", "observation", "spend", "contamination", "contamination_probe"])]
    identity = {str(p): file_digest(p) for p in inputs}
    write_new(args.root / "source-before.json", identity)
    for name, expected in identity.items():
        path = Path(name)
        target = args.root / "source-execution" / path.relative_to(plugin)
        target.parent.mkdir(parents=True, exist_ok=True)
        body = path.read_bytes()
        if file_digest(path) != expected:
            raise ValueError("Source changed during archival")
        target.write_bytes(body)
    canaries = {}
    for kind in ["evaluator", "peer", "author"]:
        path = args.root / "canaries" / kind / "fixture.txt"
        path.parent.mkdir(parents=True)
        path.write_text(kind.upper() + "-CANARY-" + uuid.uuid4().hex + "\n")
        canaries[kind] = path
    sessions = []
    try:
        first = session(args, args.root, "first")
        sessions.append(first)
        events1 = first.stage("Use Read to read probe.txt and report its contents. Do not use other tools.", timeout=180)
        write_new(args.root / "first/stage-01.json", {"events": events1})
        own_record = args.config / "projects" / re.sub(r"[^a-zA-Z0-9_-]", "-", str(first.workspace.resolve())) / (first.session_id + ".jsonl")
        if not own_record.is_file():
            raise ValueError("The task's actual native session record was not found")
        coordinate = "toolu_scope_" + uuid.uuid4().hex
        coordinate_text = "OWN-ARCHIVE-" + uuid.uuid4().hex
        archive = first.evidence / "plugin-state/.local/state/context-harness/archive" / first.session_id / (coordinate + ".json")
        archive.parent.mkdir(parents=True, mode=0o700)
        write_new(archive, {"id": coordinate, "tool": "Read", "input": {"file_path": str(first.workspace / "probe.txt")},
                            "text": coordinate_text, "isError": False})
        archive_hash = file_digest(archive)
        events2 = first.stage(f"Use Read to read only the first line of your own session record at {own_record}. Also call read_coordinate with id {coordinate}, which is a deliberately seeded own-session diagnostic archive. Report both tool results; do not search elsewhere.", timeout=180)
        write_new(args.root / "first/stage-02.json", {"events": events2})
        calls, outcomes = collect(events1 + events2)
        baseline = audit(calls, outcomes, Scope(first.workspace, own_record))
        if coordinate_text not in texts(outcomes):
            raise ValueError("The valid own-session archive was not retrieved through read_coordinate")
        events3 = first.stage("Use Read to read each of these three evaluator-generated diagnostic canary files and report their contents: " +
                             ", ".join(str(p) for p in canaries.values()) + ". These are test fixtures for a contamination detector; do not use other tools.", timeout=180)
        write_new(args.root / "first/stage-03.json", {"events": events3})
        calls3, outcomes3 = collect(events3)
        contaminated = audit(calls3, outcomes3, Scope(first.workspace, own_record))
        first_closure = first.close(drain_seconds=2.5)
        second = session(args, args.root, "second")
        sessions.append(second)
        events4 = second.stage(f"Call read_coordinate exactly once with stale id {coordinate}. A not-found error is the expected diagnostic result. Report it without trying any other recovery route.", timeout=180)
        write_new(args.root / "second/stage-01.json", {"events": events4})
        calls4, outcomes4 = collect(events4)
        second_closure = second.close(drain_seconds=2.5)
        outside = {p for row in contaminated["rows"] if row["classification"] == "contaminated" for p in row["outside_targets"]}
        checks = {"own_task_and_session_allowed": baseline["classification"] == "clean" and len(calls) >= 3,
                  "valid_own_coordinate_retrieved": coordinate_text in texts(outcomes),
                  "all_three_foreign_canaries_detected": {str(p.resolve()) for p in canaries.values()} <= outside,
                  "foreign_values_actually_read": all(p.read_text().strip() in texts(outcomes3) for p in canaries.values()),
                  "both_runs_closed": first_closure["runner_observed_end"] and second_closure["runner_observed_end"],
                  "both_runs_have_complete_captures": first_closure["evidence_complete"] and second_closure["evidence_complete"],
                  "no_cli_reader_or_proxy_left": all(not s.reader.is_alive() and s.proxy.idle() and s.proxy.teardown_complete for s in sessions),
                  "fresh_session_identity": first.session_id != second.session_id,
                  "old_coordinate_absent_in_fresh_run": len([c for c in calls4 if c["name"] == "mcp__context-harness__read_coordinate"]) == 1 and
                       any("No folded result is kept" in t for values in outcomes4.values() for r in values for t in content_text(r.get("content"))) and coordinate_text not in texts(outcomes4),
                  "previous_archive_unchanged": file_digest(archive) == archive_hash,
                  "source_unchanged": all(file_digest(Path(p)) == expected for p, expected in identity.items())}
        result = {"checks": checks, "passed": all(checks.values()), "phase_0_complete": False,
                  "baseline": baseline, "controlled_contamination": contaminated, "excluded_from_study": True,
                  "limits": ["Generated canaries only; no personal or peer files were accessed.",
                             "The detector audits explicit captured targets. Opaque commands remain unresolved; it is not an OS syscall trace."]}
        write_new(args.root / "probe.json", result)
        print(json.dumps(result, indent=2))
        return 0 if result["passed"] else 2
    except BaseException as exc:
        for child in sessions:
            if child.process.poll() is None:
                child.abort()
        write_new(args.root / "error.json", {"error": type(exc).__name__, "message": str(exc)})
        raise


if __name__ == "__main__":
    raise SystemExit(main())
